const currency = new Intl.NumberFormat('en-GB', { style: 'currency', currency: 'GBP', maximumFractionDigits: 0 });
const isoDate = (value) => value || '';
const referenceDate = Date.parse('2026-10-22T00:00:00Z');
const day = 86400000;
const shiftDate = (value, days) => (value ? new Date(Date.parse(value) - days * day).toISOString().slice(0, 10) : null);

export function generateRecords(count) {
  return Array.from({ length: count }, (_, id) => {
    const sample = sampleRecords[id % sampleRecords.length];
    const batch = Math.floor(id / sampleRecords.length);
    if (batch === 0) return { ...sample, id, synthetic: false };
    const originalPrice = sample.originalPrice + (batch % 25) * 5000;
    const totalReductionAmount =
      id % 5 === 0 ? 0 : Math.round((originalPrice * (sample.totalReductionAmount / sample.originalPrice)) / 50) * 50;
    const listedDate = shiftDate(sample.listedDate, batch % 90);
    const matchCriteria = ['full', 'partial', 'none'][id % 3];
    return {
      ...sample,
      id,
      synthetic: true,
      property: `${sample.property} (demo ${batch + 1})`,
      originalPrice,
      currentPrice: originalPrice - totalReductionAmount,
      totalReductionAmount,
      totalReductionPercentage: Number(((totalReductionAmount / originalPrice) * 100).toFixed(1)),
      listedDate,
      latestPriceReduction: totalReductionAmount ? shiftDate(sample.latestPriceReduction, batch % 90) : null,
      latestFallThrough: id % 4 ? shiftDate(sample.latestFallThrough, batch % 90) : null,
      weeksOnMarket: Math.floor((referenceDate - Date.parse(listedDate)) / (7 * day)),
      bedrooms: 1 + (id % 5),
      propertyType: ['House', 'Bungalow', 'Flat'][id % 3],
      matchCriteria,
      criteriaMatch: { full: 'Full match', partial: 'Partial match', none: 'No match' }[matchCriteria],
      criteriaCount: { full: 3, partial: 1, none: 0 }[matchCriteria],
      // Generated rows do not pretend to have real property identifiers/coordinates.
      udprn: null,
      umrrn: null,
      latitude: null,
      longitude: null,
    };
  });
}

